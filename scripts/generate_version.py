#!/usr/bin/env python3
"""Synchronize the public header and ESP-IDF manifest from library.json."""

import argparse
import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
VERSION_PATTERN = re.compile(r"(0|[1-9][0-9]{0,4})\.(0|[1-9][0-9]{0,4})\.(0|[1-9][0-9]{0,4})")
# Keep the version on the first content line so it cannot be part of another scalar.
IDF_VERSION_LINE = re.compile(rb"""^(?:version|"version"|'version')[ \t]*:([^\r\n]*)""", re.MULTILINE)
IDF_VERSION_VALUE = re.compile(rb'[ \t]+"[^"\r\n]*"([ \t]+(?:#[^\r\n]*)?)?')


def load_version(path: Path) -> tuple[str, tuple[int, int, int]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    version = data.get("version") if isinstance(data, dict) else None
    match = VERSION_PATTERN.fullmatch(version) if isinstance(version, str) else None
    if match is not None:
        major, minor, patch = (int(part) for part in match.groups())
        if max(major, minor, patch) <= 65535:
            return version, (major, minor, patch)
    raise ValueError(f"{path}: expected version X.Y.Z with components from 0 to 65535")


def render_version_header(version: str, components: tuple[int, int, int]) -> bytes:
    major, minor, patch = components
    return f'''/**
 * @file Version.h
 * @brief Compile-time and linked version information for TMP11x.
 *
 * Generated by scripts/generate_version.py from library.json.
 */

#pragma once

#include <cstdint>

namespace TMP11x {{

/// @brief Major component of the header version.
constexpr std::uint16_t VERSION_MAJOR = {major};

/// @brief Minor component of the header version.
constexpr std::uint16_t VERSION_MINOR = {minor};

/// @brief Patch component of the header version.
constexpr std::uint16_t VERSION_PATCH = {patch};

/// @brief Null-terminated header version in X.Y.Z form.
constexpr char VERSION[] = "{version}";

/// @brief Return the version compiled into the linked TMP11x library.
/// @return Null-terminated X.Y.Z string valid for the lifetime of the program.
const char* version() noexcept;

}}  // namespace TMP11x
'''.encode("utf-8")


def sync_outputs(check_only: bool) -> bool:
    version, components = load_version(ROOT / "library.json")

    idf = ROOT / "idf_component.yml"
    current_idf = idf.read_bytes()
    fields = list(IDF_VERSION_LINE.finditer(current_idf))
    if len(fields) != 1:
        raise ValueError(f"{idf}: expected exactly one top-level version field")
    field = fields[0]
    leading_lines = current_idf[:field.start()].splitlines()
    if any(line.strip() and not line.lstrip().startswith(b"#") for line in leading_lines):
        raise ValueError(f"{idf}: expected the version on the first content line")
    value = IDF_VERSION_VALUE.fullmatch(field[1])
    if value is None:
        raise ValueError(f"{idf}: expected a double-quoted version on one line")
    expected_idf = (
        current_idf[:field.start(1)]
        + f' "{version}"'.encode("ascii")
        + (value[1] or b"")
        + current_idf[field.end(1):]
    )

    header = ROOT / "include/TMP11x/Version.h"
    try:
        current_header = header.read_bytes()
    except FileNotFoundError:
        current_header = None

    candidates = (
        (header, current_header, render_version_header(version, components)),
        (idf, current_idf, expected_idf),
    )
    updates = [(path, current, expected) for path, current, expected in candidates if current != expected]
    if check_only:
        for path, _, _ in updates:
            print(f"Out of date: {path}", file=sys.stderr)
        return not updates

    # Check existing mirrors for writability before changing either one.
    for path, current, _ in updates:
        if current is not None:
            with path.open("r+b"):
                pass
    for path, _, expected in updates:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
        print(f"Updated: {path}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("sync", "check"))
    check_only = parser.parse_args().command == "check"
    try:
        clean = sync_outputs(check_only)
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    return 1 if check_only and not clean else 0


if __name__ == "__main__":
    raise SystemExit(main())
